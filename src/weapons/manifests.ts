const MANIFEST_MAP: Record<WeaponId, WeaponManifest> = Object.fromEntries(
  WEAPON_MANIFESTS.map((m) => [m.id, m])
) as Record<WeaponId, WeaponManifest>;

export const ARMORY_WEAPONS: readonly ArmoryWeaponItem[] = WEAPON_MANIFESTS.map(
  (m) => m.catalog
);

export function getWeaponManifest(weaponId: string): WeaponManifest {
  if (isWeaponId(weaponId)) {
    return MANIFEST_MAP[weaponId];
  }
  return MANIFEST_MAP.ak15;
}

export function getShortWeaponLabel(weaponId: string): string {
  return isWeaponId(weaponId)
    ? MANIFEST_MAP[weaponId].shortLabel
    : weaponId.toUpperCase();
}

export function matchesArmoryCategory(
  item: ArmoryWeaponItem,
  filter: ArmoryCategory
): boolean {
  if (filter === 'all') return true;
  const typeTag = `${item.weaponTypeCn ?? ''} ${item.categoryCn}`;
  const isPistol = item.category === 'pistol' || typeTag.includes('手枪');
  const isSmg =
    item.id === 'mp5' || item.category === 'smg' || typeTag.includes('冲锋');
  const isSniper =
    item.id === 'm82a1' ||
    item.id === 'awm' ||
    item.category === 'sniper' ||
    typeTag.includes('狙击') ||
    typeTag.includes('反器材');

  if (filter === 'pistol') return isPistol;
  if (filter === 'smg') return isSmg;
  if (filter === 'sniper') return isSniper;
  if (filter === 'assault') return !isPistol && !isSmg && !isSniper;
  return true;
}
