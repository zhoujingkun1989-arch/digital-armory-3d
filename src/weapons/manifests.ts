const MANIFEST_MAP: Record<WeaponId, WeaponManifest> = Object.fromEntries(
  WEAPON_MANIFESTS.map((m) => [m.id, m])
) as Record<WeaponId, WeaponManifest>;

export const ARMORY_WEAPONS: readonly ArmoryWeaponItem[] = WEAPON_MANIFESTS.map(
  (m) => m.catalog
);

export function getWeaponManifest(weaponId: string): WeaponManifest {
  if (isWeaponId(weaponId)) {
    return MANIFEST_MAP[weaponId];
  }
  return MANIFEST_MAP.ak15;
}

export function getShortWeaponLabel(weaponId: string): string {
  return isWeaponId(weaponId)
    ? MANIFEST_MAP[weaponId].shortLabel
    : weaponId.toUpperCase();
}

export function matchesArmoryCategory(
  item: ArmoryWeaponItem,
  filter: ArmoryCategory
): boolean {
  if (filter === 'all') return true;
  if (
    item.category === 'ordnance' ||
    item.category === 'armor' ||
    item.category === 'archery' ||
    item.category === 'pistol' ||
    item.category === 'smg' ||
    item.category === 'lmg' ||
    item.category === 'sniper' ||
    item.category === 'shotgun'
  ) {
    return filter === item.category;
  }
  const typeTag = `${item.weaponTypeCn ?? ''} ${item.categoryCn}`;
  const isPistol = typeTag.includes('手枪');
  const isLmg = item.id === 'm249' || typeTag.includes('机枪');
  const isSmg = item.id === 'mp5' || typeTag.includes('冲锋');
  const isSniper =
    item.id === 'm82a1' ||
    item.id === 'awm' ||
    typeTag.includes('狙击') ||
    typeTag.includes('反器材');
  const isArchery =
    item.id === 'lift33' ||
    item.id === 'r500' ||
    typeTag.includes('弓') ||
    typeTag.includes('弩');
  const isShotgun = item.id === 'benellim4' || typeTag.includes('霰弹');
  const isArmor =
    item.id === 'ztz99a' ||
    item.id === 'm1a2' ||
    item.id === 'leopard2a7' ||
    item.id === 'tiger1' ||
    typeTag.includes('坦克') ||
    typeTag.includes('重装');
  const isOrdnance =
    item.id === 'gau8' ||
    typeTag.includes('航炮') ||
    typeTag.includes('航空重武') ||
    typeTag.includes('航空机炮') ||
    typeTag.includes('火炮');

  if (filter === 'pistol') return isPistol;
  if (filter === 'lmg') return isLmg;
  if (filter === 'smg') return isSmg;
  if (filter === 'sniper') return isSniper;
  if (filter === 'shotgun') return isShotgun;
  if (filter === 'archery') return isArchery;
  if (filter === 'armor') return isArmor;
  if (filter === 'ordnance') return isOrdnance;
  if (filter === 'assault') {
    return (
      !isPistol &&
      !isLmg &&
      !isSmg &&
      !isSniper &&
      !isShotgun &&
      !isArchery &&
      !isArmor &&
      !isOrdnance
    );
  }
  return true;
}
